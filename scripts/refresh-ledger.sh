#!/usr/bin/env bash
# Regenerates js/ledger-data.js from the GitHub contribution calendar.
# Needs the gh CLI, logged in. Usage: bash scripts/refresh-ledger.sh [login]
set -euo pipefail

LOGIN="${1:-RemiPelloux}"
OUT="$(dirname "$0")/../js/ledger-data.js"
QUERY='query($login: String!) { user(login: $login) { contributionsCollection {
  contributionCalendar { weeks { contributionDays { date contributionCount } } } } } }'
FILTER='.data.user.contributionsCollection.contributionCalendar.weeks
  | map(.contributionDays[])
  | "// Generated by scripts/refresh-ledger.sh. Do not edit by hand.\n"
    + "export const LEDGER_START = \"\(.[0].date)\";\n"
    + "export const LEDGER_COUNTS = \(map(.contributionCount) | tojson);"'

gh api graphql -f query="$QUERY" -f login="$LOGIN" --jq "$FILTER" > "$OUT"
